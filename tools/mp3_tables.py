# Writes src/wasm/mp3_tables.h: the MPEG-1 Layer III tables the standard defines (ISO/IEC 11172-3 Annex B) — the 34 Huffman code
# tables and the synthesis window — read from the system's own MP3 libraries (no network here; the tables are data of the standard,
# identical in every implementation): the Huffman tables from libshine's table array (located through its relocations), the window
# from libavcodec's decoder table. Every Huffman table is checked to be a complete prefix code (Kraft sum 1, no code a prefix of
# another) and the window's peak is checked against the standard's 1.144989014. Usage: python3 tools/mp3_tables.py
import struct, subprocess, re, sys
SHINE = '/usr/lib/x86_64-linux-gnu/libshine.so.3'; AVC = '/usr/lib/x86_64-linux-gnu/libavcodec.so.60'
d = open(SHINE, 'rb').read(); secs = {}
for line in subprocess.run(['readelf', '-SW', SHINE], capture_output=True, text=True).stdout.splitlines():
    m = re.search(r'\]\s+(\S+)\s+\S+\s+([0-9a-f]+)\s+([0-9a-f]+)\s+([0-9a-f]+)', line)
    if m: secs[m.group(1)] = (int(m.group(2), 16), int(m.group(3), 16), int(m.group(4), 16))
def foff(va):
    for n, (a, o, sz) in secs.items():
        if a <= va < a + sz and n in ('.rodata', '.data.rel.ro'): return va - a + o
    return -1
rel = {}
for line in subprocess.run(['readelf', '-rW', SHINE], capture_output=True, text=True).stdout.splitlines():
    m = re.match(r'^([0-9a-f]+)\s+[0-9a-f]+\s+R_X86_64_RELATIVE\s+([0-9a-f]+)', line.strip())
    if m: rel[int(m.group(1), 16)] = int(m.group(2), 16)
t2 = d.find(struct.pack('<9H', 1, 2, 1, 3, 1, 1, 3, 2, 0)); ptr = [k for k, v in rel.items() if foff(v) == t2][0]; base = ptr - 16 - 2 * 32
tabs = []
for t in range(34):
    e = base + t * 32; xlen, ylen, linbits, linmax = struct.unpack('<4I', d[foff(e):foff(e) + 16]); hb, hl, n = rel.get(e + 16), rel.get(e + 24), xlen * ylen
    codes = list(struct.unpack('<%dH' % n, d[foff(hb):foff(hb) + 2 * n])) if hb and n else []; lens = list(d[foff(hl):foff(hl) + n]) if hl and n else []
    if lens:
        assert abs(sum(2.0 ** -l for l in lens) - 1) < 1e-9, t; cs = sorted(format(c, '0%db' % l) for c, l in zip(codes, lens))
        assert all(not b.startswith(a) for a, b in zip(cs, cs[1:])), t
    tabs.append((xlen, ylen, linbits, codes, lens))
a = open(AVC, 'rb').read(); off = a.find(struct.pack('<11i', 0, -1, -1, -1, -1, -1, -1, -2, -2, -2, -2)); win = list(struct.unpack('<257i', a[off:off + 257 * 4])); assert win[256] == 75038
out = ['/* MPEG-1 Layer III tables (ISO/IEC 11172-3, Annex B): the 34 Huffman code tables and the analysis/synthesis window.',
       '   Data defined by the standard (needed by any encoder to be decodable). Generated by tools/mp3_tables.py — do not edit. */', '#define MP3_HTN 34']
codes, lens, meta = [], [], []
for (xl, yl, lb, c, l) in tabs: meta.append('{%d, %d, %d, %d, %d}' % (xl, yl, lb, len(codes), len(c))); codes += c; lens += l
out += ['static const unsigned short HCODE[%d] = {%s};' % (len(codes), ','.join(map(str, codes))), 'static const unsigned char HLEN[%d] = {%s};' % (len(lens), ','.join(map(str, lens))),
        '/* xlen, ylen, linbits, offset into HCODE/HLEN, count */', 'static const int HTAB[MP3_HTN][5] = {%s};' % ','.join(meta),
        '/* the synthesis window D[0..256] in units of 2^-16 (the analysis window is C[i] = D[i] / 32; D[512-i] = ±D[i]) */', 'static const int ENWIN[257] = {%s};' % ','.join(map(str, win))]
open(sys.argv[1] if len(sys.argv) > 1 else 'src/wasm/mp3_tables.h', 'w').write('\n'.join(out) + '\n'); print('34 tables, %d codes; window peak %d' % (len(codes), win[256]))
